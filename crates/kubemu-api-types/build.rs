//! Filters the vendored upstream OpenAPI spec (`openapi/`, ADR 0012) down
//! to the resources in `served.rs`, and generates the static tables the
//! crate exposes:
//! - the resource table, with verbs taken from the spec's
//!   `x-kubernetes-action`s;
//! - the OpenAPI v2 document and the v3 documents as served, compact;
//! - a schema arena for every definition the served paths reach, used for
//!   pruning, structural validation and strategic merge patch.

#[path = "served.rs"]
mod served;

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use kubemu_env_real::build_script::{out_dir, read_tracked, write_if_changed};
use serde_json::{Map, Value};
use served::{SERVED, Served};

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    println!("cargo::rerun-if-changed=served.rs");
    let out = out_dir();

    let version = String::from_utf8(read_tracked(&root.join("openapi/VERSION")).unwrap())
        .unwrap()
        .trim()
        .to_owned();
    let swagger = read_json(&root.join("openapi/swagger.json"));

    // OpenAPI v2.
    let (v2, kept) = filter_doc(&swagger, "#/definitions/", &["definitions"]);
    write_if_changed(&out.join("openapi-v2.json"), v2.to_string().as_bytes()).unwrap();

    // OpenAPI v3, one document per served group-version.
    let mut v3_docs = Vec::new();
    for gv in served_group_versions() {
        let (path, file) = v3_names(&gv);
        let doc = read_json(&root.join("openapi/v3").join(&file));
        let (doc, _) = filter_doc(&doc, "#/components/schemas/", &["components", "schemas"]);
        let text = doc.to_string();
        let name = format!("openapi-v3-{}.json", path.replace('/', "_"));
        write_if_changed(&out.join(&name), text.as_bytes()).unwrap();
        v3_docs.push((path, name, fnv_hex(text.as_bytes())));
    }

    let mut code = String::new();
    writeln!(
        code,
        "// Generated by build.rs from openapi/ ({version}). Do not edit."
    )
    .unwrap();
    writeln!(code, "pub static KUBERNETES_VERSION: &str = {version:?};").unwrap();
    writeln!(
        code,
        "pub static OPENAPI_V2: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/openapi-v2.json\"));"
    )
    .unwrap();
    writeln!(code, "pub static OPENAPI_V3: &[OpenApiV3] = &[").unwrap();
    for (path, name, hash) in &v3_docs {
        writeln!(
            code,
            "    OpenApiV3 {{ path: {path:?}, hash: {hash:?}, document: include_str!(concat!(env!(\"OUT_DIR\"), \"/{name}\")) }},"
        )
        .unwrap();
    }
    writeln!(code, "];").unwrap();

    let schemas = SchemaGen::new(&kept);
    code.push_str(&resources(&swagger, &schemas));
    code.push_str(&schemas.emit());
    write_if_changed(&out.join("generated.rs"), code.as_bytes()).unwrap();
}

fn read_json(path: &Path) -> Value {
    let bytes = read_tracked(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    serde_json::from_slice(&bytes).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn served_group_versions() -> BTreeSet<(String, String)> {
    SERVED
        .iter()
        .map(|s| (s.group.to_owned(), s.version.to_owned()))
        .collect()
}

/// `("api/v1", "api__v1_openapi.json")` for a group-version.
fn v3_names((group, version): &(String, String)) -> (String, String) {
    let path = if group.is_empty() {
        format!("api/{version}")
    } else {
        format!("apis/{group}/{version}")
    };
    let file = format!("{}_openapi.json", path.replace('/', "__"));
    (path, file)
}

fn fnv_hex(bytes: &[u8]) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in bytes {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{h:016X}")
}

/// What a spec path addresses, if kubemu serves it.
enum Target<'a> {
    /// `/api/`, `/apis/`, `/apis/<group>/`, `/api/v1/`, `/apis/<g>/<v>/`.
    Discovery,
    Resource {
        served: &'a Served,
        subresource: Option<&'a str>,
    },
}

fn classify(path: &str) -> Option<Target<'static>> {
    let segs: Vec<&str> = path.trim_matches('/').split('/').collect();
    let (group, version, rest) = match segs.as_slice() {
        ["api"] | ["apis"] => return Some(Target::Discovery),
        ["apis", g] => {
            return SERVED
                .iter()
                .any(|s| s.group == *g)
                .then_some(Target::Discovery);
        }
        ["api", v, rest @ ..] => ("", *v, rest),
        ["apis", g, v, rest @ ..] => (*g, *v, rest),
        _ => return None,
    };
    let in_gv = |s: &&Served| s.group == group && s.version == version;
    if rest.is_empty() {
        return SERVED
            .iter()
            .any(|s| in_gv(&s))
            .then_some(Target::Discovery);
    }
    let (watch, rest) = match rest {
        ["watch", rest @ ..] => (true, rest),
        _ => (false, rest),
    };
    let rest = match rest {
        ["namespaces", "{namespace}", rest @ ..] if !rest.is_empty() => rest,
        _ => rest,
    };
    let (plural, rest) = rest.split_first()?;
    let served = SERVED.iter().filter(in_gv).find(|s| s.plural == *plural)?;
    let subresource = match rest {
        [] | ["{name}"] => None,
        ["{name}", sub] if !watch => Some(*served.subresources.iter().find(|s| *s == sub)?),
        _ => return None,
    };
    Some(Target::Resource {
        served,
        subresource,
    })
}

/// Keeps the served paths of an OpenAPI document and the definitions they
/// reach. Returns the filtered document and the kept definitions.
fn filter_doc(doc: &Value, ref_prefix: &str, defs_at: &[&str]) -> (Value, BTreeMap<String, Value>) {
    let mut out = doc.as_object().unwrap().clone();
    let paths: Map<String, Value> = doc["paths"]
        .as_object()
        .unwrap()
        .iter()
        .filter(|(p, _)| classify(p).is_some())
        .map(|(p, v)| (p.clone(), v.clone()))
        .collect();
    let all_defs = defs_at.iter().fold(doc, |v, k| &v[*k]).as_object().unwrap();
    // v2 also has shared parameters, which reference definitions.
    let all_params = doc.get("parameters").and_then(Value::as_object);

    let mut defs = BTreeMap::new();
    let mut params = Map::new();
    let mut todo = Vec::new();
    collect_refs(&Value::Object(paths.clone()), &mut todo);
    while let Some(r) = todo.pop() {
        if let Some(name) = r.strip_prefix(ref_prefix) {
            if !defs.contains_key(name) {
                let d = all_defs
                    .get(name)
                    .unwrap_or_else(|| panic!("dangling $ref {r}"))
                    .clone();
                collect_refs(&d, &mut todo);
                defs.insert(name.to_owned(), d);
            }
        } else if let Some(name) = r.strip_prefix("#/parameters/") {
            if !params.contains_key(name) {
                let p = all_params.and_then(|ps| ps.get(name)).unwrap().clone();
                collect_refs(&p, &mut todo);
                params.insert(name.to_owned(), p);
            }
        } else {
            panic!("unexpected $ref {r}");
        }
    }

    out.insert("paths".into(), Value::Object(paths));
    if out.contains_key("parameters") {
        out.insert("parameters".into(), Value::Object(params));
    }
    let defs_value = Value::Object(defs.clone().into_iter().collect());
    match defs_at {
        [k] => {
            out.insert((*k).into(), defs_value);
        }
        [outer, inner] => {
            out.get_mut(*outer).unwrap()[*inner] = defs_value;
        }
        _ => unreachable!(),
    }
    (Value::Object(out), defs)
}

fn collect_refs(v: &Value, into: &mut Vec<String>) {
    match v {
        Value::Object(o) => {
            for (k, v) in o {
                match (k.as_str(), v) {
                    ("$ref", Value::String(r)) => into.push(r.clone()),
                    _ => collect_refs(v, into),
                }
            }
        }
        Value::Array(a) => a.iter().for_each(|v| collect_refs(v, into)),
        _ => {}
    }
}

fn verb_of(action: &str) -> Option<&'static str> {
    Some(match action {
        "get" => "get",
        "list" => "list",
        "watch" | "watchlist" => "watch",
        "post" => "create",
        "put" => "update",
        "patch" => "patch",
        "delete" => "delete",
        "deletecollection" => "deletecollection",
        _ => return None,
    })
}

/// The resource table, joining `SERVED` with verbs and schemas from the spec.
fn resources(swagger: &Value, schemas: &SchemaGen) -> String {
    // (plural, group, version, subresource) -> verbs
    let mut verbs: BTreeMap<(&str, &str, &str, Option<&str>), BTreeSet<&str>> = BTreeMap::new();
    for (path, item) in swagger["paths"].as_object().unwrap() {
        let Some(Target::Resource {
            served,
            subresource,
            ..
        }) = classify(path)
        else {
            continue;
        };
        let set = verbs
            .entry((served.plural, served.group, served.version, subresource))
            .or_default();
        for op in item.as_object().unwrap().values() {
            if let Some(v) = op
                .get("x-kubernetes-action")
                .and_then(Value::as_str)
                .and_then(verb_of)
            {
                set.insert(v);
            }
        }
    }

    let mut code = String::from("pub static RESOURCES: &[ResourceInfo] = &[\n");
    for s in SERVED {
        let key = |sub| (s.plural, s.group, s.version, sub);
        let main = verbs
            .get(&key(None))
            .unwrap_or_else(|| panic!("{} not in the spec", s.plural));
        // The spec has no flag for namespace scope; namespaced resources
        // have `/namespaces/{namespace}/<plural>` paths.
        let namespaced = swagger["paths"]
            .as_object()
            .unwrap()
            .keys()
            .any(|p| p.ends_with(&format!("/namespaces/{{namespace}}/{}", s.plural)));
        let schema = schemas
            .gvk(s.group, s.version, s.kind)
            .unwrap_or_else(|| panic!("no schema for {}", s.kind));
        let subs: Vec<String> = s
            .subresources
            .iter()
            .map(|sub| {
                let v = verbs
                    .get(&key(Some(sub)))
                    .unwrap_or_else(|| panic!("{}/{sub} not in the spec", s.plural));
                format!("Subresource {{ name: {sub:?}, verbs: &{:?} }}", list(v))
            })
            .collect();
        writeln!(
            code,
            "    ResourceInfo {{ group: {:?}, version: {:?}, kind: {:?}, plural: {:?}, singular: {:?}, namespaced: {namespaced}, short_names: &{:?}, categories: &{:?}, verbs: &{:?}, subresources: &[{}], schema: SchemaId({schema}) }},",
            s.group,
            s.version,
            s.kind,
            s.plural,
            s.kind.to_lowercase(),
            s.short_names,
            s.categories,
            list(main),
            subs.join(", "),
        )
        .unwrap();
    }
    code.push_str("];\n");
    code
}

fn list(v: &BTreeSet<&str>) -> Vec<String> {
    v.iter().map(|s| (*s).to_owned()).collect()
}

/// Flattens definitions into an arena of nodes. Definitions take the first
/// ids, in name order; inline schemas follow.
struct SchemaGen {
    names: BTreeMap<String, usize>,
    nodes: Vec<String>,
    gvks: BTreeMap<(String, String, String), usize>,
}

impl SchemaGen {
    fn new(defs: &BTreeMap<String, Value>) -> Self {
        let mut g = Self {
            names: defs
                .keys()
                .enumerate()
                .map(|(i, n)| (n.clone(), i))
                .collect(),
            nodes: vec![String::new(); defs.len()],
            gvks: BTreeMap::new(),
        };
        for (i, (name, def)) in defs.iter().enumerate() {
            g.nodes[i] = g.node(name, def);
            for gvk in def
                .get("x-kubernetes-group-version-kind")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
            {
                let s = |k: &str| gvk[k].as_str().unwrap().to_owned();
                g.gvks
                    .entry((s("group"), s("version"), s("kind")))
                    .or_insert(i);
            }
        }
        g
    }

    fn gvk(&self, group: &str, version: &str, kind: &str) -> Option<usize> {
        self.gvks
            .get(&(group.into(), version.into(), kind.into()))
            .copied()
    }

    fn push(&mut self, name: &str, v: &Value) -> usize {
        self.nodes.push(String::new());
        let id = self.nodes.len() - 1;
        self.nodes[id] = self.node(name, v);
        id
    }

    /// One `Node` literal. `name` is the definition being flattened, for
    /// special cases and error messages.
    fn node(&mut self, name: &str, v: &Value) -> String {
        let s = |k: &str| v.get(k).and_then(Value::as_str);
        let ty = if let Some(r) = s("$ref") {
            let target = r.strip_prefix("#/definitions/").unwrap();
            format!("Ty::Ref(SchemaId({}))", self.names[target])
        } else {
            match (name, s("type"), s("format")) {
                ("io.k8s.apimachinery.pkg.api.resource.Quantity", ..) => "Ty::Quantity".into(),
                (_, _, Some("int-or-string")) => "Ty::IntOrString".into(),
                (_, Some("string"), _) => "Ty::String".into(),
                (_, Some("integer"), _) => "Ty::Integer".into(),
                (_, Some("number"), _) => "Ty::Number".into(),
                (_, Some("boolean"), _) => "Ty::Boolean".into(),
                (_, Some("array"), _) => {
                    let items = self.push(name, &v["items"]);
                    format!("Ty::Array(SchemaId({items}))")
                }
                (_, Some("object") | None, _) => self.object(name, v),
                (_, Some(other), _) => panic!("{name}: unknown type {other}"),
            }
        };
        let opt = |k: &str| match s(k) {
            Some(x) => format!("Some({x:?})"),
            None => "None".into(),
        };
        let map_keys: Vec<&str> = v
            .get("x-kubernetes-list-map-keys")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .map(|k| k.as_str().unwrap())
            .collect();
        let preserve = v
            .get("x-kubernetes-preserve-unknown-fields")
            .and_then(Value::as_bool)
            .unwrap_or(false);
        format!(
            "Node {{ ty: {ty}, ext: Ext {{ patch_strategy: {}, merge_key: {}, list_type: {}, map_keys: &{map_keys:?}, map_type: {}, format: {}, preserve_unknown_fields: {preserve} }} }}",
            opt("x-kubernetes-patch-strategy"),
            opt("x-kubernetes-patch-merge-key"),
            opt("x-kubernetes-list-type"),
            opt("x-kubernetes-map-type"),
            opt("format"),
        )
    }

    fn object(&mut self, name: &str, v: &Value) -> String {
        let props = v.get("properties").and_then(Value::as_object);
        let additional = v.get("additionalProperties");
        match (props, additional) {
            (Some(props), None) => {
                let fields: Vec<String> = props
                    .iter()
                    .map(|(k, p)| format!("({k:?}, SchemaId({}))", self.push(name, p)))
                    .collect();
                let required: Vec<&str> = v
                    .get("required")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                    .map(|k| k.as_str().unwrap())
                    .collect();
                format!(
                    "Ty::Object {{ fields: &[{}], required: &{required:?} }}",
                    fields.join(", ")
                )
            }
            (None, Some(Value::Object(_))) => {
                let values = self.push(name, additional.unwrap());
                format!("Ty::Map(SchemaId({values}))")
            }
            // `type: object` with nothing else (RawExtension, FieldsV1):
            // anything goes, nothing is pruned.
            (None, None) => "Ty::Any".into(),
            _ => panic!("{name}: object with both properties and additionalProperties"),
        }
    }

    fn emit(&self) -> String {
        let mut code = String::from("pub static NODES: &[Node] = &[\n");
        for n in &self.nodes {
            writeln!(code, "    {n},").unwrap();
        }
        code.push_str("];\npub static DEFINITIONS: &[(&str, SchemaId)] = &[\n");
        for (n, i) in &self.names {
            writeln!(code, "    ({n:?}, SchemaId({i})),").unwrap();
        }
        code.push_str("];\npub static GVKS: &[(&str, &str, &str, SchemaId)] = &[\n");
        for ((g, v, k), i) in &self.gvks {
            writeln!(code, "    ({g:?}, {v:?}, {k:?}, SchemaId({i})),").unwrap();
        }
        code.push_str("];\n");
        code
    }
}
